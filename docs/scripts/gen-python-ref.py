#!/usr/bin/env python3
"""Auto-generates docs/reference/python.md from crates/dealbreaker-py/python/dealbreaker/__init__.py."""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "crates/dealbreaker-py/python/dealbreaker/__init__.py"
OUT = ROOT / "docs/reference/python.md"


def format_arg(arg: ast.arg, default: ast.expr | None) -> str:
    s = arg.arg
    if arg.annotation is not None:
        s += f": {ast.unparse(arg.annotation)}"
    if default is not None:
        s += f" = {ast.unparse(default)}"
    return s


def format_signature(fn: ast.FunctionDef) -> str:
    args = fn.args
    parts: list[str] = []

    pos_args = [a for a in args.args if a.arg not in ("self", "cls")]
    pos_defaults = [None] * (len(pos_args) - len(args.defaults)) + list(args.defaults)
    for a, d in zip(pos_args, pos_defaults):
        parts.append(format_arg(a, d))

    if args.kwonlyargs:
        parts.append("*")
        for a, d in zip(args.kwonlyargs, args.kw_defaults):
            parts.append(format_arg(a, d))

    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns is not None else ""
    prefix = ""
    for dec in fn.decorator_list:
        if isinstance(dec, ast.Name) and dec.id == "classmethod":
            prefix = "@classmethod "
    return f"{prefix}{fn.name}({', '.join(parts)}){ret}"


def clean_doc(doc: str | None) -> str:
    if not doc:
        return ""
    # Convert simple reST double-backticks and :func: to Markdown
    return (
        doc.replace("``", "`")
        .replace(":func:`presets`", "`presets()`")
        .strip()
    )


def main() -> None:
    tree = ast.parse(SRC.read_text(encoding="utf-8"))
    lines: list[str] = [
        "<!-- AUTO-GENERATED by scripts/gen-docs.sh — do not edit by hand. -->",
        "",
        "# Python Reference",
        "",
        "> Auto-generated from [`crates/dealbreaker-py/python/dealbreaker/__init__.py`](https://github.com/samdobson/dealbreaker/blob/main/crates/dealbreaker-py/python/dealbreaker/__init__.py).",
        "",
        "```sh",
        "pip install dealbreaker",
        "```",
        "",
    ]

    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            lines.append("## Module Functions")
            lines.append("")
            lines.append(f"### `{format_signature(node)}`")
            doc = clean_doc(ast.get_docstring(node))
            if doc:
                lines.extend(["", doc])
            lines.append("")
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            lines.append(f"## `class {node.name}`")
            doc = clean_doc(ast.get_docstring(node))
            if doc:
                lines.extend(["", doc])
            lines.append("")
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and (
                    not item.name.startswith("_") or item.name == "__init__"
                ):
                    lines.append(f"### `{format_signature(item)}`")
                    mdoc = clean_doc(ast.get_docstring(item))
                    if mdoc:
                        lines.extend(["", mdoc])
                    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print("[gen-docs] wrote docs/reference/python.md")


if __name__ == "__main__":
    main()
