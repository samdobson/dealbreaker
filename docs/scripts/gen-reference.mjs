#!/usr/bin/env node
/**
 * Auto-generates VitePress Reference pages from Dealbreaker's source-of-truth files:
 *   - docs/schemas/rules.schema.json                -> docs/reference/rules-schema.md
 *   - docs/schemas/{state,step,solve,hint}.schema   -> docs/reference/data-formats.md
 *   - `dealbreaker list` & `dealbreaker rules <id>` -> docs/reference/presets.md
 *   - `dealbreaker --help`                          -> docs/reference/cli.md
 *   - js/src/{index,worker,types}.d.ts              -> docs/reference/javascript.md
 *   - crates/dealbreaker-ffi/include/dealbreaker.h  -> docs/reference/c-abi.md
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "../..");
const OUT_DIR = path.join(ROOT, "docs/reference");
fs.mkdirSync(OUT_DIR, { recursive: true });

const HEADER_COMMENT =
  "<!-- AUTO-GENERATED by scripts/gen-docs.sh — do not edit by hand. -->\n\n";

function writeRef(filename, content) {
  const dest = path.join(OUT_DIR, filename);
  fs.writeFileSync(dest, HEADER_COMMENT + content.trimEnd() + "\n", "utf8");
  console.log(`[gen-docs] wrote docs/reference/${filename}`);
}

function escapeTable(s) {
  if (!s) return "";
  return String(s).replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();
}

function slug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

// ---------------------------------------------------------------------------
// 1. JSON Schema -> Markdown (rules-schema.md & data-formats.md)
// ---------------------------------------------------------------------------

function formatType(prop, defs, anchorPrefix = "") {
  if (!prop) return "`any`";
  if (prop.$ref) {
    const name = prop.$ref.split("/").pop();
    if (name === "SchemaUri") return "`string`";
    return `[${name}](#${anchorPrefix}${slug(name)})`;
  }
  if (prop.allOf && prop.allOf.length === 1) {
    return formatType(prop.allOf[0], defs, anchorPrefix);
  }
  if (prop.anyOf) {
    const parts = prop.anyOf
      .filter((x) => x.type !== "null")
      .map((x) => formatType(x, defs, anchorPrefix));
    const nullable = prop.anyOf.some((x) => x.type === "null");
    return parts.join(" \\| ") + (nullable ? " \\| `null`" : "");
  }
  if (prop.oneOf) {
    const parts = prop.oneOf.map((x) => formatType(x, defs, anchorPrefix));
    return parts.join(" \\| ");
  }
  if (prop.enum) {
    return prop.enum.map((v) => `\`${JSON.stringify(v)}\``).join(" \\| ");
  }
  if (Array.isArray(prop.type)) {
    return prop.type.map((t) => `\`${t}\``).join(" \\| ");
  }
  if (prop.type === "array") {
    const item = prop.items ? formatType(prop.items, defs, anchorPrefix) : "`any`";
    return `${item}[]`;
  }
  if (prop.type === "object" && prop.additionalProperties) {
    const val = formatType(prop.additionalProperties, defs, anchorPrefix);
    return `Record&lt;string, ${val}&gt;`;
  }
  if (prop.type) {
    return `\`${prop.type}\``;
  }
  return "`any`";
}

function formatDefault(prop) {
  if (prop.default === undefined) return "—";
  const raw = JSON.stringify(prop.default);
  if (raw.length > 36) return "*standard default*";
  return `\`${raw}\``;
}

function renderObjectTable(schema, defs, anchorPrefix = "") {
  const props = schema.properties || {};
  const required = new Set(schema.required || []);
  const keys = Object.keys(props);
  if (keys.length === 0) return "";

  const lines = [
    "| Field | Type | Default | Description |",
    "|---|---|---|---|",
  ];
  for (const key of keys) {
    const p = props[key];
    const req = required.has(key) && key !== "$schema" ? " *(required)*" : "";
    const type = formatType(p, defs, anchorPrefix);
    const def = formatDefault(p);
    const desc = escapeTable(p.description || "");
    lines.push(`| \`${key}\`${req} | ${type} | ${def} | ${desc} |`);
  }
  return lines.join("\n");
}

function renderVariants(variants, defs, anchorPrefix = "") {
  const lines = [];
  for (const v of variants) {
    if (v.type === "string" && v.enum && v.enum.length === 1) {
      const desc = v.description ? ` — ${v.description.replace(/\n+/g, " ").trim()}` : "";
      lines.push(`- \`"${v.enum[0]}"\`${desc}`);
    } else if (v.type === "object" && v.properties) {
      const keys = Object.keys(v.properties);
      const desc = v.description ? ` — ${v.description.replace(/\n+/g, " ").trim()}` : "";
      if (keys.length === 1) {
        const k = keys[0];
        const inner = v.properties[k];
        const t = formatType(inner, defs, anchorPrefix);
        lines.push(`- \`{ "${k}": ... }\` (${t})${desc}`);
      } else {
        const summary = keys
          .map((k) => {
            const inner = v.properties[k];
            if (inner.enum && inner.enum.length === 1) {
              return `"${k}": ${JSON.stringify(inner.enum[0])}`;
            }
            return `"${k}"`;
          })
          .join(", ");
        lines.push(`- \`{ ${summary} }\`${desc}`);
        const subTable = renderObjectTable(v, defs, anchorPrefix);
        if (subTable) {
          lines.push("\n" + subTable + "\n");
        }
      }
    } else {
      const desc = v.description ? ` — ${v.description.replace(/\n+/g, " ").trim()}` : "";
      lines.push(`- ${formatType(v, defs, anchorPrefix)}${desc}`);
    }
  }
  return lines.join("\n");
}

function renderDefinition(name, def, defs, headingLevel = "##", anchorPrefix = "") {
  const lines = [`${headingLevel} ${name} {#${anchorPrefix}${slug(name)}}`];
  if (def.description) {
    lines.push("", def.description.trim());
  }
  if (def.properties) {
    lines.push("", renderObjectTable(def, defs, anchorPrefix));
  } else if (def.oneOf) {
    lines.push("", renderVariants(def.oneOf, defs, anchorPrefix));
  } else if (def.anyOf) {
    lines.push("", renderVariants(def.anyOf, defs, anchorPrefix));
  } else if (def.enum) {
    lines.push("", def.enum.map((e) => `- \`${JSON.stringify(e)}\``).join("\n"));
  } else if (def.type) {
    lines.push("", `Type: ${formatType(def, defs, anchorPrefix)}`);
  }
  return lines.join("\n");
}

function genRulesSchema() {
  const schema = JSON.parse(
    fs.readFileSync(path.join(ROOT, "docs/schemas/rules.schema.json"), "utf8")
  );
  const defs = schema.definitions || {};

  const parts = [
    "# Rules Schema Reference",
    "",
    "> Looking for a guided walkthrough instead? Start with the [Build a Custom Game tutorial](/tutorials/custom-game).",
    "",
    "This page is auto-generated from [`docs/schemas/rules.schema.json`](https://github.com/samdobson/dealbreaker/blob/main/docs/schemas/rules.schema.json). Add `\"$schema\"` to the top of any game JSON file for live autocomplete and validation in VS Code or JetBrains:",
    "",
    "```json",
    "{",
    '  "$schema": "https://raw.githubusercontent.com/samdobson/dealbreaker/main/docs/schemas/rules.schema.json",',
    '  "name": "My Game",',
    '  "groups": [ ... ]',
    "}",
    "```",
    "",
    "## Top-Level `Rules` Object",
    "",
    schema.description || "",
    "",
    renderObjectTable(schema, defs),
    "",
    "## Definitions",
    "",
  ];

  // Order definitions logically: core structures first, then alphabetical for the rest
  const preferredOrder = [
    "Pack",
    "Suit",
    "Color",
    "GroupRules",
    "PileKind",
    "Build",
    "BuildBy",
    "Dir",
    "EmptyRule",
    "MoveUnit",
    "Layout",
    "PileOverride",
    "StockRules",
    "RedealRules",
    "RedealHow",
    "DealStep",
    "RemovalRules",
    "RemovalKind",
    "Adjacency",
    "ScoreRules",
    "Hands",
    "PokerTable",
    "PokerScoring",
    "PokerPoints",
    "CribbageRules",
    "CribbagePoints",
    "WinRule",
    "SearchHints",
  ];
  const allNames = Object.keys(defs).filter((n) => n !== "SchemaUri");
  const ordered = [
    ...preferredOrder.filter((n) => allNames.includes(n)),
    ...allNames.filter((n) => !preferredOrder.includes(n)).sort(),
  ];

  for (const name of ordered) {
    parts.push(renderDefinition(name, defs[name], defs, "###"), "");
  }

  writeRef("rules-schema.md", parts.join("\n"));
}

function genDataFormats() {
  const files = [
    { file: "state.schema.json", prefix: "state-", title: "Position (`StateData`)" },
    { file: "step.schema.json", prefix: "step-", title: "Move / Action (`Step`)" },
    { file: "solve-options.schema.json", prefix: "solve-", title: "Search Options (`SolveOptions`)" },
    { file: "hint-options.schema.json", prefix: "hint-", title: "Hint Options (`HintOptions`)" },
    { file: "grade-options.schema.json", prefix: "grade-", title: "Grade Options (`GradeOptions`)" },
  ];

  const parts = [
    "# Data Formats Reference",
    "",
    "JSON schemas for positions, moves, and search/hint options—used consistently across the CLI (`--state`, `--json`, `serve`), WebAssembly/JS, Python, and C ABI.",
    "",
  ];

  for (const entry of files) {
    const schema = JSON.parse(
      fs.readFileSync(path.join(ROOT, "docs/schemas", entry.file), "utf8")
    );
    const defs = schema.definitions || {};
    parts.push(`## ${entry.title}`);
    if (schema.description) {
      parts.push("", schema.description.trim());
    }
    if (schema.properties) {
      parts.push("", renderObjectTable(schema, defs, entry.prefix));
    } else if (schema.oneOf) {
      parts.push("", renderVariants(schema.oneOf, defs, entry.prefix));
    }
    for (const [defName, def] of Object.entries(defs)) {
      parts.push("", renderDefinition(defName, def, defs, "###", entry.prefix));
    }
    parts.push("");
  }

  writeRef("data-formats.md", parts.join("\n"));
}

