// 3. TypeScript Declarations -> javascript.md
// ---------------------------------------------------------------------------

function cleanJsDoc(raw) {
  if (!raw) return "";
  return raw
    .trim()
    .replace(/^\/\*\*/, "")
    .replace(/\*\/$/, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, ""))
    .join("\n")
    .trim();
}

function parseDtsClass(src, className) {
  const re = new RegExp(`export class ${className}\\s*\\{([\\s\\S]*?)\\n\\}`);
  const m = re.exec(src);
  if (!m) return null;
  const before = src.slice(0, m.index).trimEnd();
  const docMatch = before.match(/\/\*\*((?:(?!\*\/)[\s\S])*)\*\/$/);
  const classDoc = docMatch ? cleanJsDoc(docMatch[0]) : "";
  const body = m[1];
  const members = [];
  const memberRe = /(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?^\s*((?:static\s+)?[a-zA-Z0-9_]+\([^)]*\)(?::\s*[^;]+)?);/gm;
  let mm;
  while ((mm = memberRe.exec(body)) !== null) {
    members.push({
      doc: mm[1] ? cleanJsDoc(`/**${mm[1]}*/`) : "",
      sig: mm[2].replace(/\s+/g, " ").trim(),
    });
  }
  return { classDoc, members };
}

function parseDtsFunctions(src) {
  const fns = [];
  const re = /(?:\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*)?^export function\s+([^;]+);/gm;
  let m;
  while ((m = re.exec(src)) !== null) {
    fns.push({
      doc: m[1] ? cleanJsDoc(`/**${m[1]}*/`) : "",
      sig: m[2].replace(/\s+/g, " ").trim(),
    });
  }
  return fns;
}

function genJsRef() {
  const indexSrc = fs.readFileSync(path.join(ROOT, "js/src/index.d.ts"), "utf8");
  const workerSrc = fs.readFileSync(path.join(ROOT, "js/src/worker.d.ts"), "utf8");
  const typesSrc = fs.readFileSync(path.join(ROOT, "js/src/types.d.ts"), "utf8");

  const topFns = parseDtsFunctions(indexSrc);
  const solverClass = parseDtsClass(indexSrc, "Solver");
  const workerClass = parseDtsClass(workerSrc, "WorkerSolver");

  const parts = [
    "# JavaScript / TypeScript Reference",
    "",
    "> Auto-generated from [`js/src/index.d.ts`](https://github.com/samdobson/dealbreaker/blob/main/js/src/index.d.ts), [`worker.d.ts`](https://github.com/samdobson/dealbreaker/blob/main/js/src/worker.d.ts), and [`types.d.ts`](https://github.com/samdobson/dealbreaker/blob/main/js/src/types.d.ts).",
    "",
    "```sh",
    "npm install dealbreaker",
    "```",
    "",
    "## Module Exports (`dealbreaker`)",
    "",
  ];

  for (const fn of topFns) {
    parts.push(`### \`${fn.sig}\``);
    if (fn.doc) parts.push("", fn.doc);
    parts.push("");
  }

  if (solverClass) {
    parts.push("## `class Solver`");
    if (solverClass.classDoc) parts.push("", solverClass.classDoc);
    parts.push("", "| Method | Description |", "|---|---|");
    for (const m of solverClass.members) {
      parts.push(`| \`${escapeTable(m.sig)}\` | ${escapeTable(m.doc)} |`);
    }
    parts.push("");
  }

  if (workerClass) {
    parts.push("## `class WorkerSolver` (`dealbreaker/worker`)");
    if (workerClass.classDoc) parts.push("", workerClass.classDoc);
    parts.push("", "| Method | Description |", "|---|---|");
    for (const m of workerClass.members) {
      parts.push(`| \`${escapeTable(m.sig)}\` | ${escapeTable(m.doc)} |`);
    }
    parts.push("");
  }

  // Extract result & option types from the bottom of types.d.ts (from StateData onward)
  const stateIdx = typesSrc.indexOf("/**\n * A position keyed by group name.");
  const coreTypes = stateIdx >= 0 ? typesSrc.slice(stateIdx).trim() : typesSrc.trim();

  parts.push(
    "## Core Data & Result Types",
    "",
    "For the full `Rules` type tree, see the [Rules Schema Reference](/reference/rules-schema).",
    "",
    "```ts",
    coreTypes,
    "```"
  );

  writeRef("javascript.md", parts.join("\n"));
}

