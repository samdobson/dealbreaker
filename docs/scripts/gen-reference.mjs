function genCAbiRef() {
  const hdr = fs.readFileSync(
    path.join(ROOT, "crates/dealbreaker-ffi/include/dealbreaker.h"),
    "utf8"
  );

  const typedefs = [];
  const funcs = [];

  const blockRe = /\/\*\*([\s\S]*?)\*\/\s*\n([\s\S]*?);/g;
  let m;
  while ((m = blockRe.exec(hdr)) !== null) {
    const doc = cleanJsDoc(`/**${m[1]}*/`);
    const decl = m[2].replace(/\s+/g, " ").trim();
    if (decl.startsWith("typedef ")) {
      typedefs.push({ doc, decl });
    } else {
      funcs.push({ doc, decl });
    }
  }

  const parts = [
    "# C ABI Reference",
    "",
    "> Auto-generated from [`crates/dealbreaker-ffi/include/dealbreaker.h`](https://github.com/samdobson/dealbreaker/blob/main/crates/dealbreaker-ffi/include/dealbreaker.h).",
    "",
    "Build the shared/static library with `cargo build --release -p dealbreaker-ffi`, or an Apple XCFramework with `./scripts/build-xcframework.sh`.",
    "",
    "## Opaque Handles",
    "",
  ];

  for (const t of typedefs) {
    parts.push(`- \`${t.decl};\` — ${t.doc}`);
  }

  parts.push("", "## Functions", "");

  for (const f of funcs) {
    const nameMatch = f.decl.match(/(\w+)\s*\(/);
    const fnName = nameMatch ? nameMatch[1] : f.decl;
    parts.push(`### \`${fnName}\``, "", "```c", `${f.decl};`, "```");
    if (f.doc) parts.push("", f.doc);
    parts.push("");
  }

  writeRef("c-abi.md", parts.join("\n"));
}

