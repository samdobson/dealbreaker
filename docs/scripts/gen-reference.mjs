function resolveCliBinary() {
  if (process.env.DEALBREAKER_BIN) return [process.env.DEALBREAKER_BIN, []];
  const releaseBin = path.join(ROOT, "target/release/dealbreaker");
  if (fs.existsSync(releaseBin)) return [releaseBin, []];
  const debugBin = path.join(ROOT, "target/debug/dealbreaker");
  if (fs.existsSync(debugBin)) return [debugBin, []];
  return ["cargo", ["run", "-q", "-p", "dealbreaker-cli", "--"]];
}

function runCli(args) {
  const [bin, prefix] = resolveCliBinary();
  return execFileSync(bin, [...prefix, ...args], {
    cwd: ROOT,
    encoding: "utf8",
  });
}

function summarizeWin(win) {
  if (!win || win === "all_on_foundations") return "All cards on foundations";
  if (win.empty) return `Empty ${win.empty.join(", ")}`;
  if (win.count) return `${win.count.cards} cards on ${win.count.group}`;
  if (win.at_most_piles) return `≤ ${win.at_most_piles.piles} pile(s) in ${win.at_most_piles.group}`;
  if (win.rows) return `Complete rows in ${win.rows.group}`;
  if (win.score) return `Score ≥ ${win.score.at_least}`;
  return JSON.stringify(win);
}

function genPresets() {
  const listOut = runCli(["list"]);
  const presets = listOut
    .trim()
    .split("\n")
    .map((line) => {
      const m = line.match(/^(\S+)\s+(.+)$/);
      return m ? { id: m[1].trim(), name: m[2].trim() } : null;
    })
    .filter(Boolean);

  const parts = [
    "# Built-in Presets Reference",
    "",
    `Dealbreaker ships with **${presets.length} built-in games**. Every preset is a standard [Rules JSON](/reference/rules-schema) definition—you can inspect any preset with \`dealbreaker rules <id>\` and tweak it into a custom variant.`,
    "",
    "## All Presets",
    "",
    "| Preset ID | Name | Packs | Groups | Win Condition |",
    "|---|---|---|---|---|",
  ];

  const details = [];
  for (const p of presets) {
    const rawJson = runCli(["rules", p.id]).trim();
    const rules = JSON.parse(rawJson);
    const copies = rules.pack?.copies ?? 1;
    const jokers = rules.pack?.jokers ? ` + ${rules.pack.jokers} joker(s)` : "";
    const packLabel = `${copies} pack${copies === 1 ? "" : "s"}${jokers}`;
    const groupsSummary = (rules.groups || [])
      .map((g) => `${g.count ?? 1} ${g.name}`)
      .join(", ");
    const winLabel = summarizeWin(rules.win);

    parts.push(
      `| [\`${p.id}\`](#${slug(p.id)}) | ${escapeTable(p.name)} | ${packLabel} | ${escapeTable(groupsSummary)} | ${escapeTable(winLabel)} |`
    );

    details.push(
      `### ${p.name} (\`${p.id}\`) {#${slug(p.id)}}`,
      "",
      `- **Pack:** ${packLabel}`,
      `- **Groups:** ${groupsSummary}`,
      `- **Win:** ${winLabel}`,
      "",
      `<details>`,
      `<summary>View JSON rules for ${p.id}</summary>`,
      "",
      "```json",
      rawJson,
      "```",
      "",
      `</details>`,
      ""
    );
  }

  parts.push("", "## Preset Details & JSON", "", ...details);
  writeRef("presets.md", parts.join("\n"));
}

